-- ============================================================
-- codenamesduet: word pools
-- ============================================================
-- The board's 25 words came from one pool, the Codenames Duet list. They now
-- come from up to three, chosen at setup (`setup.word_pools`) and dealt in
-- equal shares (supabase/sql/codenamesduet.sql → create_game):
--
--   1  duet        Codenames Duet       the 390 words already here
--   2  codenames   Codenames            sagelga/codenames, en-EN/default
--   3  undercover  Undercover (adult)   sagelga/codenames, en-EN/undercover
--
-- The table stores the pool's number, since a name on every row would be
-- repeated a few hundred times; setup stores the name, and create_game maps one
-- to the other.
--
-- **A word belongs to the lowest-numbered list it appears in.** The primary
-- key stays on `word`, and the lists go in in pool order with `on conflict
-- (word) do nothing`, so a word already in an earlier list keeps that list's
-- number: 68 of the undercover list's 390 are in list 1 or 2, leaving 322.
-- Words are stored lowercase, as the first 390 are. Checked before import:
-- no British spellings, no word that differs from another only by a hyphen or
-- a space, and nothing longer than 11 letters.
--
-- Sources, fetched 2026-10-07:
--   https://raw.githubusercontent.com/sagelga/codenames/refs/heads/main/wordlist/en-EN/default/wordlist.txt
--   https://raw.githubusercontent.com/sagelga/codenames/refs/heads/main/wordlist/en-EN/undercover/wordlist.txt
--
-- Also a DATA migration: every game and saved setup so far was dealt from the
-- Duet list, so `word_pools: ["duet"]` is written into each codenamesduet
-- game's `common.games.setup`, the copy of it in `static_game_data.setup`
-- (the page reads its setup rows off that copy), and each club's saved
-- setup, `common.clubs_gametypes.default_setup`. Idempotent: only rows without
-- the key are touched. `status_changed_at` is not touched, so the club list
-- keeps its order and dates.

alter table codenamesduet.word_pool add column pool smallint not null default 1;
alter table codenamesduet.word_pool alter column pool drop default;
alter table codenamesduet.word_pool
  add constraint word_pool_pool_check check (pool between 1 and 3);

